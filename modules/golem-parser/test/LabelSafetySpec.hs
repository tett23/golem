{- | golem-parser ADR 0007: every label of the grammar is safe, so the
grammar with its labels removed (StrippedGrammar, generated by
scripts/gen-parser.sh) accepts exactly the inputs that the parser parses
without diagnostics.
-}
module LabelSafetySpec (tests) where

import Control.Monad (forM)
import Data.Either (isRight)
import Data.List (isSuffixOf, sort)
import Data.Text (Text)
import Data.Text qualified as T
import Data.Text.IO qualified as TIO
import Golem.Parser (parse)
import Golem.Syntax (FileId (..))
import Hedgehog
import Hedgehog.Gen qualified as Gen
import Hedgehog.Range qualified as Range
import ParserSpec (fragment, fragments)
import StrippedGrammar qualified as Stripped
import System.Directory (doesDirectoryExist, listDirectory)
import System.FilePath ((</>))
import Test.Tasty
import Test.Tasty.HUnit hiding (assert)
import Test.Tasty.Hedgehog

-- | The two grammars agree on an input.
agree :: Text -> Bool
agree src = isRight (Stripped.parse src) == null (snd (parse (FileId 0) src))

-- | Fails with the first inputs on which the grammars disagree.
allAgree :: [Text] -> Assertion
allAgree inputs = case filter (not . agree) inputs of
  [] -> pure ()
  bad -> assertFailure (show (length bad) <> " inputs disagree, for example " <> show (take 5 bad))

-- | The fragments of ParserSpec and the ones that reach the fixed rules.
pieces :: [Text]
pieces = fragments <> ["*", "[= ", "x", "|", "| 1 |", "|abc", "\n  ", "**[= 1]"]

-- | Every concatenation of up to three pieces.
upToThree :: [Text]
upToThree = [""] <> pieces <> [a <> b | a <- pieces, b <- pieces] <> [a <> b <> c | a <- pieces, b <- pieces, c <- pieces]

fixtures :: FilePath
fixtures = "../golem-driver/test/fixtures"

-- | The Golem sources of the sample project and of the two books.
sources :: IO [FilePath]
sources = do
  sample <- walk (fixtures </> "sample")
  pure (sample <> [fixtures </> "tempest" </> "tempest.gm", fixtures </> "kanikosen" </> "kanikosen.gm"])
  where
    walk dir = do
      entries <- sort <$> listDirectory dir
      concat
        <$> forM
          entries
          ( \e -> do
              let path = dir </> e
              isDir <- doesDirectoryExist path
              pure' isDir path
          )
    pure' isDir path
      | isDir = walk path
      | ".gm" `isSuffixOf` path = pure [path]
      | otherwise = pure []

{- | One character deleted, and one doubled, at evenly spaced positions:
100 of them, or 20 in a file longer than 20000 characters.
-}
mutations :: Text -> [Text]
mutations src =
  let n = T.length src
      k = if n > 20000 then 20 else 100
      positions = [i * n `div` k | n > 0, i <- [0 .. k - 1]]
   in concat [[T.take i src <> T.drop (i + 1) src, T.take (i + 1) src <> T.drop i src] | i <- positions]

tests :: TestTree
tests =
  testGroup
    "label safety (ADR 0007)"
    [ testCase "every concatenation of up to three fragments" $ allAgree upToThree,
      testProperty "arbitrary fragments" $ withTests 500 $ property $ do
        src <- forAll (T.concat <$> Gen.list (Range.linear 0 30) fragment)
        assert (agree src),
      testCase "the fixtures and their mutations" $ do
        files <- sources
        assertBool "fixtures found" (length files >= 3)
        srcs <- mapM TIO.readFile files
        allAgree (srcs <> concatMap mutations srcs)
    ]
