#!/bin/sh
# Generates the Vertical_Orientation table of UAX #50 for golem-layout
# (golem-driver ADR 0015) from Unicode's VerticalOrientation.txt.
#
#   sh scripts/gen-vertical-orientation.sh path/to/VerticalOrientation.txt
#
# The file is read from the path given; nothing is downloaded. Adjacent
# ranges with the same value are merged; code points the file does not
# list take the value of its "@missing" line, which comes before the data.
set -eu
if [ "$#" -ne 1 ]; then
  echo "usage: $0 VerticalOrientation.txt" >&2
  exit 2
fi
in=$1
out="$(dirname "$0")/../modules/golem-layout/src/Golem/Layout/Orientation/Table.hs"
tmp="$out.tmp"
LC_ALL=C awk '
function hex(s,    i, n, c) {
  n = 0
  s = toupper(s)
  for (i = 1; i <= length(s); i++) {
    c = index("0123456789ABCDEF", substr(s, i, 1))
    if (c == 0) { print "bad code point: " s > "/dev/stderr"; exit 1 }
    n = n * 16 + c - 1
  }
  return n
}
function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
# one entry, in the layout of fourmolu (trailing commas)
function flush() {
  if (have) {
    if (count > 0) printf ",\n"
    printf "%s(0x%04X, 0x%04X, %s)", (count == 0 ? "  [ " : "    "), lo, hi, val
    count++
  }
}
NR == 1 {
  version = $0
  sub(/^#[ \t]*/, "", version)
  sub(/[ \t\r]+$/, "", version)
}
/^#[ \t]*@missing:/ {
  line = $0
  sub(/^#[ \t]*@missing:[ \t]*/, "", line)
  split(line, m, ";")
  if (trim(m[1]) != "0000..10FFFF" || missing != "") { print "unexpected @missing line: " $0 > "/dev/stderr"; exit 1 }
  missing = trim(m[2])
  if (missing != "U" && missing != "R" && missing != "Tu" && missing != "Tr") { print "bad value: " $0 > "/dev/stderr"; exit 1 }
  next
}
{
  line = $0
  sub(/#.*/, "", line)
  if (trim(line) == "") next
  split(line, f, ";")
  cp = trim(f[1]); v = trim(f[2])
  if (v != "U" && v != "R" && v != "Tu" && v != "Tr") { print "bad value: " $0 > "/dev/stderr"; exit 1 }
  if (index(cp, "..") > 0) { a = hex(substr(cp, 1, index(cp, "..") - 1)); b = hex(substr(cp, index(cp, "..") + 2)) }
  else { a = hex(cp); b = a }
  if (b < a || (have && a <= hi)) { print "ranges out of order: " $0 > "/dev/stderr"; exit 1 }
  if (!header) {
    if (missing == "") { print "no @missing line before the data" > "/dev/stderr"; exit 1 }
    header = 1
    print "{- | Generated by scripts/gen-vertical-orientation.sh; do not edit."
    print "The Vertical_Orientation property of UAX #50 (golem-driver ADR 0015),"
    print "from " version " of the Unicode Character Database"
    print "(https://www.unicode.org/Public/UCD/latest/ucd/VerticalOrientation.txt)."
    print "Unicode data: (c) Unicode, Inc., under the Unicode License v3"
    print "(https://www.unicode.org/license.txt)."
    print "-}"
    print "module Golem.Layout.Orientation.Table"
    print "  ( Vo (..),"
    print "    unicodeVersion,"
    print "    missingValue,"
    print "    voRanges,"
    print "  )"
    print "where"
    print ""
    print "-- | The four values of the property, as the file writes them."
    print "data Vo = U | R | Tu | Tr"
    print "  deriving stock (Eq, Show)"
    print ""
    print "-- | The version of VerticalOrientation.txt the table comes from."
    print "unicodeVersion :: String"
    print "unicodeVersion = \"" version "\""
    print ""
    print "-- | The value of a code point the file does not list (its @missing line)."
    print "missingValue :: Vo"
    print "missingValue = " missing
    print ""
    print "-- | The listed ranges, ascending and disjoint, adjacent ranges of one value merged."
    print "voRanges :: [(Int, Int, Vo)]"
    print "voRanges ="
  }
  if (have && v == val && a == hi + 1) { hi = b; next }
  flush()
  have = 1; lo = a; hi = b; val = v
}
END {
  if (!header) { print "no data" > "/dev/stderr"; exit 1 }
  flush()
  printf "\n  ]\n"
}
' "$in" >"$tmp" || {
  rm -f "$tmp"
  exit 1
}
mv "$tmp" "$out"
