#!/bin/sh
# Generates the Latin sort-key tables of root ADR 0470 from Unicode 17.0.0.
# No files are downloaded. Inputs, in order:
#   UnicodeData.txt  2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c
#   Scripts.txt      9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf
# Sources: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
#          https://www.unicode.org/Public/17.0.0/ucd/Scripts.txt
set -eu
[ "$#" -eq 2 ] || { echo "usage: $0 UnicodeData.txt Scripts.txt" >&2; exit 2; }
hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1"; else shasum -a 256 "$1"; fi | awk '{print $1}'
}
[ "$(hash_file "$1")" = 2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c ] || { echo 'UnicodeData.txt is not the pinned Unicode 17.0.0 input' >&2; exit 1; }
[ "$(hash_file "$2")" = 9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf ] || { echo 'Scripts.txt is not the pinned Unicode 17.0.0 input' >&2; exit 1; }
output="$(dirname "$0")/../modules/golem-unicode/src/Golem/Unicode/LatinTable.hs"
trap 'rm -f "$output.tmp"' EXIT HUP INT TERM
LC_ALL=C awk '
function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
function hex(s,    n,i,v) {
  n = 0; s = toupper(s)
  for (i=1; i<=length(s); i++) { v=index("0123456789ABCDEF",substr(s,i,1)); if(!v) exit 1; n=n*16+v-1 }
  return n
}
function ranges(name,flags,    i,start,first) {
  print name " :: [(Int, Int, Bool)]"
  print name " ="
  start=-1; first=1
  for(i=0;i<=1114112;i++) {
    if(i in flags) { if(start<0) start=i }
    else if(start>=0) {
      printf "%s(0x%04X, 0x%04X, True)", (first ? "  [ " : ",\n    "), start, i-1
      first=0; start=-1
    }
  }
  print "\n  ]\n"
}
function base(cp,    parts,n,first,i) {
  if(cp in memo) return memo[cp]
  if(!(cp in decomposition)) return cp
  n=split(decomposition[cp],parts," ")
  first=base(hex(parts[1]))
  if(!(first in latin)) return memo[cp]=cp
  for(i=2;i<=n;i++) if(!(hex(parts[i]) in nonstarter)) return memo[cp]=cp
  return memo[cp]=first
}
NR==FNR {
  line=$0; sub(/#.*/,"",line)
  if(split(line,fields,";")<2 || trim(fields[2])!="Latin") next
  n=split(trim(fields[1]),points,/\.\./)
  low=hex(points[1]); high=(n==2 ? hex(points[2]) : low)
  for(i=low;i<=high;i++) latin[i]=1
  next
}
{
  split($0,fields,";"); cp=hex(fields[1])
  if(fields[4]+0!=0) nonstarter[cp]=1
  if(fields[6]!="" && fields[6] !~ /^</) decomposition[cp]=fields[6]
  if(cp in latin && fields[14]!="") lower[cp]=hex(fields[14])
}
END {
  print "{- | Generated by scripts/gen-unicode-latin.sh; do not edit."
  print "Latin Script, nonzero combining classes, canonical"
  print "Latin bases and simple lowercase from Unicode 17.0.0 UnicodeData.txt"
  print "and Scripts.txt (https://www.unicode.org/Public/17.0.0/ucd/)."
  print "Unicode data: (c) Unicode, Inc., Unicode License v3 (UNICODE-LICENSE)."
  print "-}"
  print "module Golem.Unicode.LatinTable"
  print "  ( latinRanges,"
  print "    nonstarterRanges,"
  print "    latinBases,"
  print "    latinLowercase,"
  print "  )"
  print "where\n"
  ranges("latinRanges",latin)
  ranges("nonstarterRanges",nonstarter)
  print "latinBases :: [(Int, Int)]\nlatinBases ="
  first=1
  for(i=0;i<1114112;i++) if(i in decomposition) {
    b=base(i)
    if(b!=i && b in latin) { printf "%s(0x%04X, 0x%04X)", (first ? "  [ " : ",\n    "), i,b; first=0 }
  }
  print "\n  ]\n"
  print "latinLowercase :: [(Int, Int)]\nlatinLowercase ="
  first=1
  for(i=0;i<1114112;i++) if(i in lower) { printf "%s(0x%04X, 0x%04X)", (first ? "  [ " : ",\n    "), i,lower[i]; first=0 }
  print "\n  ]"
}
' "$2" "$1" > "$output.tmp"
mv "$output.tmp" "$output"
