# same_as EXPECTED FILE NAME
same_as() {
  if cmp -s "$1" "$2"; then ok; else
    ng "$3"
    diff "$1" "$2" | sed 's/^/  /'
  fi
}
run gen_em
expect "gen-embedded: the modules" 0
