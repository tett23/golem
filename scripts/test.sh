#!/bin/sh
# Tests of the scripts that run only by hand
# (docs/adr/0078-tests-for-release-and-hand-run-scripts.md):
# gen-vertical-orientation.sh, fixtures/copy-fonts.sh and
# fixtures/fetch-public-domain.sh. Each script writes into the repository
# it is in, so each test runs a copy of it in a fake root in a temporary
# directory; nothing here uses the network. The changes job of
# .github/workflows/ci.yml runs this.
#
# wasmtime-licenses.sh has no test: it runs curl, git, jq, nm, strings, ar,
# cargo and rustup, too many to fake, and release/licenses.sh checks its
# output at a release (docs/adr/0078).
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
WORK=$(mktemp -d)
trap 'rm -rf "${WORK:?}"' EXIT
FAILURES=0
COUNT=0

ok() { COUNT=$((COUNT + 1)); }
ng() {
  COUNT=$((COUNT + 1))
  FAILURES=$((FAILURES + 1))
  printf 'FAIL: %s\n' "$1"
  if [ -s "$WORK/out" ]; then sed 's/^/  stdout: /' "$WORK/out"; fi
  if [ -s "$WORK/err" ]; then sed 's/^/  stderr: /' "$WORK/err"; fi
  return 0
}

# run CMD...: stdout to $WORK/out, stderr to $WORK/err, the exit code to $CODE
run() {
  CODE=0
  "$@" >"$WORK/out" 2>"$WORK/err" || CODE=$?
}

# expect NAME CODE: checks the exit code of the last run
expect() {
  if [ "$CODE" != "$2" ]; then
    ng "$1 (exit code $CODE, expected $2)"
    return 0
  fi
  ok
}

# fake DIR NAME BODY: an executable DIR/NAME that runs the shell code BODY
fake() {
  mkdir -p "$1"
  printf '#!/bin/sh\n%s\n' "$3" >"$1/$2"
  chmod +x "$1/$2"
}

# ---------------------------------------------------------------- gen-vertical-orientation.sh

GV=$WORK/vo
TABLE=$GV/modules/golem-layout/src/Golem/Layout/Orientation/Table.hs
mkdir -p "$GV/scripts" "$(dirname "$TABLE")"
cp "$HERE/gen-vertical-orientation.sh" "$GV/scripts/gen-vertical-orientation.sh"
gen_vo() { sh "$GV/scripts/gen-vertical-orientation.sh" "$@"; }
# the data: a @missing line, comments, two adjacent ranges and a code point
# of U merged into one range, and a range of Tu
cat >"$GV/vo.txt" <<'EOF'
# VerticalOrientation-16.0.0.txt
# Date: 2024-04-30

# @missing: 0000..10FFFF; R

0000..001F    ; R  # Cc    [32] <control-0000>..<control-001F>
00A7          ; U  # Po         SECTION SIGN
3000..3001    ; U  # Zs   [2] IDEOGRAPHIC SPACE..IDEOGRAPHIC COMMA
3002          ; U  # Po         IDEOGRAPHIC FULL STOP
3003..3004    ; Tu # So   [2] DITTO MARK..JAPANESE INDUSTRIAL STANDARD SYMBOL
EOF
cat >"$GV/expected" <<'EOF'
{- | Generated by scripts/gen-vertical-orientation.sh; do not edit.
The Vertical_Orientation property of UAX #50 (golem-driver ADR 0015),
from VerticalOrientation-16.0.0.txt of the Unicode Character Database
(https://www.unicode.org/Public/UCD/latest/ucd/VerticalOrientation.txt).
Unicode data: (c) Unicode, Inc., under the Unicode License v3
(https://www.unicode.org/license.txt).
-}
module Golem.Layout.Orientation.Table
  ( Vo (..),
    unicodeVersion,
    missingValue,
    voRanges,
  )
where

-- | The four values of the property, as the file writes them.
data Vo = U | R | Tu | Tr
  deriving stock (Eq, Show)

-- | The version of VerticalOrientation.txt the table comes from.
unicodeVersion :: String
unicodeVersion = "VerticalOrientation-16.0.0.txt"

-- | The value of a code point the file does not list (its @missing line).
missingValue :: Vo
missingValue = R

-- | The listed ranges, ascending and disjoint, adjacent ranges of one value merged.
voRanges :: [(Int, Int, Vo)]
voRanges =
  [ (0x0000, 0x001F, R),
    (0x00A7, 0x00A7, U),
    (0x3000, 0x3002, U),
    (0x3003, 0x3004, Tu)
  ]
EOF
run gen_vo "$GV/vo.txt"
expect "gen-vertical-orientation: the table" 0
if cmp -s "$GV/expected" "$TABLE"; then ok; else
  ng "gen-vertical-orientation: the table is the one expected"
  diff "$GV/expected" "$TABLE" | sed 's/^/  /'
fi
cp "$TABLE" "$GV/before"
# no @missing line before the data
grep -v '@missing' "$GV/vo.txt" >"$GV/no-missing.txt"
run gen_vo "$GV/no-missing.txt"
expect "gen-vertical-orientation: no @missing line" 1
if cmp -s "$GV/before" "$TABLE" && [ ! -e "$TABLE.tmp" ]; then ok; else ng "gen-vertical-orientation: a failure leaves the table as it was"; fi
# ranges out of order
printf '# VerticalOrientation-16.0.0.txt\n# @missing: 0000..10FFFF; R\n3000 ; U\n0000 ; R\n' >"$GV/order.txt"
run gen_vo "$GV/order.txt"
expect "gen-vertical-orientation: ranges out of order" 1
# a value that is not one of the four
printf '# VerticalOrientation-16.0.0.txt\n# @missing: 0000..10FFFF; R\n3000 ; X\n' >"$GV/value.txt"
run gen_vo "$GV/value.txt"
expect "gen-vertical-orientation: a bad value" 1
if cmp -s "$GV/before" "$TABLE"; then ok; else ng "gen-vertical-orientation: the failures leave the table as it was"; fi
run gen_vo
expect "gen-vertical-orientation: no argument" 2

# ---------------------------------------------------------------- fixtures/copy-fonts.sh

CF=$WORK/copy-fonts
FIX=$CF/modules/golem-driver/test/fixtures
mkdir -p "$CF/scripts/fixtures" "$FIX/tempest/fonts" "$FIX/kanikosen/fonts"
cp "$HERE/fixtures/copy-fonts.sh" "$CF/scripts/fixtures/copy-fonts.sh"
for f in SourceSerifVariable-Roman.ttf LICENSE-SourceSerif.txt; do printf '%s\n' "$f" >"$FIX/tempest/fonts/$f"; done
for f in NotoSerifJP-Regular.otf LICENSE-NotoSerifJP.txt; do printf '%s\n' "$f" >"$FIX/kanikosen/fonts/$f"; done
run sh "$CF/scripts/fixtures/copy-fonts.sh"
expect "copy-fonts: runs" 0
# fonts_are BOOK FILE...: the fonts/ of BOOK has exactly the FILEs, copies
# of those of the fixture they come from
fonts_are() {
  book=$1
  shift
  if [ "$(cd "$FIX/pd/$book/fonts" 2>/dev/null && ls | LC_ALL=C sort)" != "$(printf '%s\n' "$@" | LC_ALL=C sort)" ]; then
    ng "copy-fonts: the fonts of $book"
    return 0
  fi
  for f in "$@"; do
    if [ "$(cat "$FIX/pd/$book/fonts/$f")" != "$f" ]; then
      ng "copy-fonts: $f of $book is the copy"
      return 0
    fi
  done
  ok
}
for book in merry-wives frogs snark elements-of-style nightmare-abbey; do
  fonts_are "$book" SourceSerifVariable-Roman.ttf LICENSE-SourceSerif.txt
done
for book in koya-hijiri ichiaku-no-suna haru-to-shura taira-no-masakado ushiyama-hotel; do
  fonts_are "$book" NotoSerifJP-Regular.otf LICENSE-NotoSerifJP.txt
done
if [ "$(cd "$FIX/pd" && ls | wc -l | tr -d ' ')" = 10 ]; then ok; else ng "copy-fonts: the ten books"; fi
rm "$FIX/kanikosen/fonts/LICENSE-NotoSerifJP.txt"
run sh "$CF/scripts/fixtures/copy-fonts.sh"
expect "copy-fonts: a licence that is missing" 1

# ---------------------------------------------------------------- fixtures/fetch-public-domain.sh

# The fake curl writes a text whose SHA-256 is not the pinned one; the
# fake cabal and golem write their names to $FP/calls, so that a
# conversion after the mismatch shows.
FP=$WORK/fetch-public-domain
mkdir -p "$FP/root/scripts/fixtures" "$FP/root/modules/golem-driver/test/fixtures"
cp "$HERE/fixtures/fetch-public-domain.sh" "$FP/root/scripts/fixtures/fetch-public-domain.sh"
fake "$FP/root/scripts/fixtures" copy-fonts.sh "echo copy-fonts >>\"$FP/calls\""
fake "$FP/bin" curl "
while [ \$# -gt 0 ]; do
  case \$1 in -o) out=\$2; shift 2 ;; *) shift ;; esac
done
echo 'not the text' >\"\$out\""
fake "$FP/bin" cabal "echo cabal >>\"$FP/calls\""
fake "$FP/bin" golem "echo golem >>\"$FP/calls\""
run env PATH="$FP/bin:$PATH" GOLEM="$FP/bin/golem" CABAL="$FP/bin/cabal" sh "$FP/root/scripts/fixtures/fetch-public-domain.sh"
expect "fetch-public-domain: a text whose SHA-256 does not match" 1
if grep -q 'SHA-256 mismatch for https://www.gutenberg.org/cache/epub/23042/pg23042.txt' "$WORK/err"; then ok; else ng "fetch-public-domain: the mismatch names the URL"; fi
if [ ! -e "$FP/calls" ]; then ok; else ng "fetch-public-domain: nothing is converted after the mismatch"; fi

# ----------------------------------------------------------------
printf '%s tests, %s failures\n' "$COUNT" "$FAILURES"
[ "$FAILURES" -eq 0 ]
