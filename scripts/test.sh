cp "$EMOD" "$GE/before-explain"
# fails CONTENT-OF-diagnostics.md LINE NAME: the run fails at LINE of
# docs/diagnostics.md and leaves both modules as they were
fails() {
  printf "$1" >"$GE/docs/diagnostics.md"
  run gen_em
  expect "gen-embedded: $3" 1
  if grep -qF "docs/diagnostics.md:$2:" "$WORK/err"; then ok; else ng "gen-embedded: $3 names line $2"; fi
  if cmp -s "$GE/before-version" "$VMOD" && cmp -s "$GE/before-explain" "$EMOD" &&
    [ ! -e "$VMOD.tmp" ] && [ ! -e "$EMOD.tmp" ]; then ok; else ng "gen-embedded: $3 leaves the modules as they were"; fi
}
fails 'a\nb\n\tc\n' 3 "a tab"
fails 'a\n\001b\n' 2 "U+0001"
fails 'a\000b\n' 1 "U+0000"
fails 'a\nb\n\177\n' 3 "U+007F"
fails 'a\r\n' 1 "a carriage return"
cp "$GE/with-newline.md" "$GE/docs/diagnostics.md"
printf '0.1.0\001\n' >"$GE/VERSION"
run gen_em
expect "gen-embedded: U+0001 in VERSION" 1
if grep -qF "VERSION:1:" "$WORK/err" && cmp -s "$GE/before-version" "$VMOD" && cmp -s "$GE/before-explain" "$EMOD"; then ok; else ng "gen-embedded: U+0001 in VERSION names line 1 and leaves the modules as they were"; fi
run gen_em x
expect "gen-embedded: an argument" 2

