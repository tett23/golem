#!/bin/sh
# Generates the two modules of golem-driver that embed files of the
# repository (docs/adr/0203), in place of Template Haskell, which the build
# for wasm cannot run in a package that depends on golem-font:
#
#   modules/golem-driver/src/Golem/Driver/Version/Embedded.hs   VERSION
#   modules/golem-driver/src/Golem/Driver/Explain/Embedded.hs   docs/diagnostics.md
#
#   sh scripts/gen-embedded.sh
#
# Each line of a file becomes one string literal, and the module joins them
# with newlines, so the constant is the file byte for byte and a change of
# one line of the file changes one line of the module. Only \ and " are
# escaped; UTF-8 is written as it is. A tab or another control character
# (U+0000 to U+001F, U+007F) fails with the line number, and neither module
# is written. CI runs this and checks that the modules have no diff.
set -eu
if [ "$#" -ne 0 ]; then
  echo "usage: $0" >&2
  exit 2
fi
ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC=$ROOT/modules/golem-driver/src/Golem/Driver

# gen FILE MODULE NAME USER OUT: the module MODULE at OUT with the constant
# NAME, the content of FILE (relative to the root), which USER embeds
gen() {
  # the last byte is a newline (or the file is empty): the list ends with ""
  if [ -z "$(tail -c 1 "$ROOT/$1")" ]; then nl=1; else nl=0; fi
  # NUL becomes U+0001, which fails as well: awk cannot hold NUL
  LC_ALL=C tr '\000' '\001' <"$ROOT/$1" | LC_ALL=C awk -v path="$1" -v module="$2" -v name="$3" -v user="$4" -v nl="$nl" '
function esc(s,    out, i) {
  out = ""
  while ((i = match(s, /[\\"]/)) > 0) {
    out = out substr(s, 1, i - 1) "\\" substr(s, i, 1)
    s = substr(s, i + 1)
  }
  return out s
}
function item(s) {
  printf "%s\"%s\"", (count == 0 ? "    [ " : ",\n      "), esc(s)
  count++
}
BEGIN {
  for (i = 1; i < 32; i++) bad[i] = sprintf("%c", i)
  bad[32] = sprintf("%c", 127)
  print "{- | Generated by scripts/gen-embedded.sh; do not edit."
  print "The content of " path ", embedded by " user " (docs/adr/0203)."
  print "-}"
  print "module " module
  print "  ( " name ","
  print "  )"
  print "where"
  print ""
  print "import Data.Text (Text)"
  print "import Data.Text qualified as T"
  print ""
  print "-- | The content of " path ", byte for byte."
  print name " :: Text"
  print name " ="
  print "  T.intercalate"
  print "    \"\\n\""
}
{
  for (i = 1; i <= 32; i++)
    if (index($0, bad[i])) {
      printf "%s:%d: a tab or a control character\n", path, NR > "/dev/stderr"
      failed = 1
      exit 1
    }
  item($0)
}
END {
  if (failed) exit 1
  if (nl) item("")
  printf "\n    ]\n"
}
' >"$5.tmp"
}

VOUT=$SRC/Version/Embedded.hs
EOUT=$SRC/Explain/Embedded.hs
mkdir -p "$SRC/Version" "$SRC/Explain"
if gen VERSION Golem.Driver.Version.Embedded versionText Golem.Driver.Version "$VOUT" &&
  gen docs/diagnostics.md Golem.Driver.Explain.Embedded documentText Golem.Driver.Explain "$EOUT"; then
  mv "$VOUT.tmp" "$VOUT"
  mv "$EOUT.tmp" "$EOUT"
else
  rm -f "$VOUT.tmp" "$EOUT.tmp"
  exit 1
fi
