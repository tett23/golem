#!/bin/sh
# Generates root ADR 0470 bibliography warning script ranges from Unicode 17.0.0.
# Source: https://www.unicode.org/Public/17.0.0/ucd/Scripts.txt
# No files are downloaded.
set -eu
[ "$#" -eq 1 ] || { echo "usage: $0 Scripts.txt" >&2; exit 2; }
hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1"; else shasum -a 256 "$1"; fi | awk '{print $1}'
}
[ "$(hash_file "$1")" = 9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf ] || { echo 'Scripts.txt is not the pinned Unicode 17.0.0 input' >&2; exit 1; }
output="$(dirname "$0")/../modules/golem-unicode/src/Golem/Unicode/ScriptTable.hs"
trap 'rm -f "$output.tmp"' EXIT HUP INT TERM
LC_ALL=C awk '
function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
function hex(s,    n,i,v) {
  n=0; s=toupper(s)
  for(i=1;i<=length(s);i++) { v=index("0123456789ABCDEF",substr(s,i,1)); if(!v) exit 1; n=n*16+v-1 }
  return n
}
{
  line=$0; sub(/#.*/,"",line)
  if(split(line,fields,";")<2) next
  script=trim(fields[2]); if(script!="Han" && script!="Hiragana" && script!="Katakana") next
  n=split(trim(fields[1]),points,/\.\./)
  low=hex(points[1]); high=(n==2 ? hex(points[2]) : low)
  for(i=low;i<=high;i++) selected[i]=1
}
END {
  print "{- | Generated by scripts/gen-unicode-script.sh; do not edit."
  print "Han, Hiragana and Katakana Scripts from Unicode 17.0.0 Scripts.txt."
  print "Source: https://www.unicode.org/Public/17.0.0/ucd/Scripts.txt"
  print "Unicode data: (c) Unicode, Inc., Unicode License v3 (UNICODE-LICENSE)."
  print "-}"
  print "module Golem.Unicode.ScriptTable (hanOrKanaRanges) where\n"
  print "hanOrKanaRanges :: [(Int, Int, Bool)]\nhanOrKanaRanges ="
  start=-1; first=1
  for(i=0;i<=1114112;i++) {
    if(i in selected) { if(start<0) start=i }
    else if(start>=0) {
      printf "%s(0x%04X, 0x%04X, True)", (first ? "  [ " : ",\n    "),start,i-1
      first=0; start=-1
    }
  }
  print "\n  ]"
}
' "$1" > "$output.tmp"
mv "$output.tmp" "$output"
