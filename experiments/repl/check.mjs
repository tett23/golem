  check('R1 string escapes', '"a\\nb"\n', ['"a\\nb"']);
  check('R2 unknown then arithmetic', 'missing\n2 + 3\n',['5'],['E02100'],1);
  check('R2 syntax then arithmetic','1 + )\n4\n',['4'],['E01100'],1);
  check('R2 type then arithmetic','1 + "x"\n5\n',['5'],['E02101'],1);
  check('R2 evaluation then arithmetic','1 / 0\n6\n',['6'],['0'],1);
  check('R2 pure requirements','File.read "secret.txt"\n7\n',['7'],['E05101'],1);
  check('R3 definitions do not persist','x = 42\nx\n8\n',['8'],['E01100','E02100'],1);
  check('R3 explicit multiline','1 +\n  2\n',['3']);
  check('R3 unterminated block','(1\n',[],['E01101'],1);
  check('R4 blank and EOF','\n \t\n',[]);
  check('R4 last line without newline','9',['9']);
  check('R5 exact 4096 bytes',' '.repeat(4095)+'1\n',['1']);
  check('R5 single-line overflow recovers',' '.repeat(4096)+'1\n9\n',['9'],['4096'],1);
  check('R5 multiline overflow discards whole block',' '.repeat(4090)+'1 +\n'+' '.repeat(10)+'2\n3\n',['3'],['4096'],1);
  check('R5 step limit', 'List.range 1 1000000\n42\n',['42'],['E04100'],1);
  check('R5 output bound','List.range 1 3000\n1\n',['1'],['出力'],1);
  check('R5 invalid UTF-8 recovers',Buffer.from([0xff,10,49,10]),['1'],['G01001'],1);
  check('R1 exact rational, character, function',"1 / 3\n'猫'\nList.map\n",['1/3',"'猫'",'<function>']);
  check('R2 byte position after a multibyte literal','"猫" ++ unknown\n1\n',['1'],['E02100 [9,16)'],1);
  check('R2 division error covers original input','1 / 0\n1\n',['1'],['G02003 [0,5)'],1);
  check('R3 declarations inside a block never run','1\nother = 2\nother\n',['1'],['E01100','E02100'],1);
  check('R5 exact output limit','"'+('x'.repeat(4094))+'"\n',['"'+('x'.repeat(4094))+'"']);
  check('R5 oversize Unicode is counted by bytes', '"'+('猫'.repeat(1365))+'"\n0\n',['0'],['入力'],1);
  check('R2 CRLF follows Emet source rules',Buffer.from('1\r\n2\n'),['2'],['G01003'],1);
  check('R2 BOM rejected at input boundary',Buffer.from([0xef,0xbb,0xbf,49,10,50,10]),['2'],['G01002'],1);
  check('R5 overlong stream is drained','x'.repeat(1048576)+'\n11\n',['11'],['入力'],1);
  check('R5 output 4097 bytes is discarded','String.replace "x" "aa" "'+'x'.repeat(2047)+'" ++ "a"\n4\n',['4'],['出力'],1);
