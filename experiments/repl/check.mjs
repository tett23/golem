  const usage=spawnSync(bin,['repl','emet','unexpected'],{input:'1\n',cwd:root,encoding:'utf8'});
  n++;if(usage.status!==2)failed++;
  console.log(JSON.stringify({name:'R4 argument usage error',ok:usage.status===2,status:usage.status}));
